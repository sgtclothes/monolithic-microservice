# 2. CONTAINER (cAdvisor)
# =====================================================================
def containers():
    L = Layout()
    proj = custom_var("project", "Compose project", ["tokoku-mono", "tokoku-ms", "tokoku-infra"])
    proj["current"] = {"text": ["tokoku-mono", "tokoku-ms"], "value": ["tokoku-mono", "tokoku-ms"]}
    for o in proj["options"]:
        o["selected"] = o["value"] in ("tokoku-mono", "tokoku-ms")
    P = 'container_label_com_docker_compose_project=~"$project", name!=""'
    by = "container_label_com_docker_compose_project, name"
    leg = "{{name}}"

    L.row("CPU")
    L.add(ts("CPU used per container (cores)",
             [("sum by (%s) (rate(container_cpu_usage_seconds_total{%s}[%s]))" % (by, P, RI), leg)], "short"), 12, 9)
    L.add(ts("CPU vs LIMIT (%)",
             [("sum by (%s) (rate(container_cpu_usage_seconds_total{%s}[%s])) / sum by (%s) ((container_spec_cpu_quota{%s} > 0) / container_spec_cpu_period{%s})" % (by, P, RI, by, P, P), leg)],
             "percentunit", "Close to 100% = the container is pinned at its CPU limit (compute bottleneck)."), 12, 9)
    L.add(ts("CPU throttling (% of periods throttled)",
             [("sum by (%s) (rate(container_cpu_cfs_throttled_periods_total{%s}[%s])) / sum by (%s) (rate(container_cpu_cfs_periods_total{%s}[%s]))" % (by, P, RI, by, P, RI), leg)],
             "percentunit", "High throttling = the kernel pauses the process because its CPU quota is used up -> latency spikes."), 12, 9)
    L.add(ts("Total CPU per architecture (all containers: app + DB + gateway + broker)",
             [("sum by (container_label_com_docker_compose_project) (rate(container_cpu_usage_seconds_total{%s}[%s]))" % (P, RI),
               "{{container_label_com_docker_compose_project}}")], "short"), 12, 9)

    L.row("Memory")
    L.add(ts("Memory working set per container",
             [("sum by (%s) (container_memory_working_set_bytes{%s})" % (by, P), leg)], "bytes"), 12, 9)
    L.add(ts("Memory vs LIMIT (%)",
             [("sum by (%s) (container_memory_working_set_bytes{%s}) / sum by (%s) (container_spec_memory_limit_bytes{%s} > 0)" % (by, P, by, P), leg)],
             "percentunit", "Close to 100% -> risk of an OOM kill."), 12, 9)
    L.add(ts("Total memory per architecture",
             [("sum by (container_label_com_docker_compose_project) (container_memory_working_set_bytes{%s})" % P,
               "{{container_label_com_docker_compose_project}}")], "bytes"), 12, 9)
    L.add(ts("OOM events",
             [("sum by (%s) (increase(container_oom_events_total{%s}[5m]))" % (by, P), leg)], "short"), 12, 9)

    L.row("Network")
    L.add(ts("Network receive per container",
             [("sum by (%s) (rate(container_network_receive_bytes_total{%s}[%s]))" % (by, P, RI), leg)], "Bps",
             "Service-to-service traffic in microservices shows up here."), 12, 9)
    L.add(ts("Network transmit per container",
             [("sum by (%s) (rate(container_network_transmit_bytes_total{%s}[%s]))" % (by, P, RI), leg)], "Bps"), 12, 9)
    return dashboard("tokoku-containers", "TokoKu: Containers (cAdvisor)", L, [proj],
                     "CPU, memory, throttling, and network per Docker container.")


