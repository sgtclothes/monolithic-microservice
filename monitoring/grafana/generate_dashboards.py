# 3. COMPARISON
# =====================================================================
def compare():
    L = Layout()
    L.add(text("How to use", (
        "Run the **same** k6 scenario against the monolith and then microservices, then pick a time range that covers both. "
        "The *stat* panels compute values **over the selected time range**, so pick a range that sits inside the steady load phase "
        "(drop the first warm-up minute) to keep it fair.")), 24, 3)

    L.row("Summary over the selected time range")
    good = [{"color": "green", "value": None}, {"color": "orange", "value": 0.3}, {"color": "red", "value": 0.5}]
    for route, label in [("/api/products", "GET /products"), ("/api/orders", "POST /orders")]:
        method = "GET" if "products" in route else "POST"
        L.add(stat(f"p95 {label}", [(
            "histogram_quantile(0.95, sum by (le, arch) (increase(http_request_duration_seconds_bucket{route=\"%s\", method=\"%s\", arch=~\"monolith|microservices\"}[$__range])))" % (route, method),
            "{{arch}}")], "s", thresholds=good), 6, 5)
    L.add(stat("Average RPS (edge)", [(
        "sum by (arch) (increase(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[$__range])) / $__range_s" % EDGE, "{{arch}}")],
        "reqps"), 6, 5)
    L.add(stat("Error rate 5xx", [(
        "sum by (arch) (increase(http_request_duration_seconds_count{%s, status_code=~\"5..\", arch=~\"monolith|microservices\"}[$__range])) / sum by (arch) (increase(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[$__range]))" % (EDGE, EDGE),
        "{{arch}}")], "percentunit", thresholds=[{"color": "green", "value": None}, {"color": "orange", "value": 0.01}, {"color": "red", "value": 0.05}]), 6, 5)
    L.add(stat("Average app CPU (cores)", [(
        "sum by (arch) (increase(process_cpu_seconds_total{arch=~\"monolith|microservices\"}[$__range])) / $__range_s", "{{arch}}")], "short", decimals=2), 6, 5)
    L.add(stat("Average CPU, all containers (cores)", [(
        "sum by (container_label_com_docker_compose_project) (increase(container_cpu_usage_seconds_total{container_label_com_docker_compose_project=~\"tokoku-mono|tokoku-ms\", name!=\"\"}[$__range])) / $__range_s",
        "{{container_label_com_docker_compose_project}}")], "short", "Includes the database, gateway, and RabbitMQ", decimals=2), 6, 5)
    L.add(stat("Efficiency: requests per CPU-second", [(
        "sum by (arch) (increase(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[$__range])) / sum by (arch) (increase(process_cpu_seconds_total{arch=~\"monolith|microservices\"}[$__range]))" % EDGE,
        "{{arch}}")], "short", "Higher is more efficient", decimals=1), 6, 5)
    L.add(stat("Current app memory", [(
        "sum by (arch) (process_resident_memory_bytes{arch=~\"monolith|microservices\"})", "{{arch}}")], "bytes"), 6, 5)

    L.row("Over time")
    L.add(ts("Throughput (edge requests/sec)",
             [("sum by (arch) (rate(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[%s]))" % (EDGE, RI), "{{arch}}")], "reqps"), 12, 9)
    L.add(ts("Error rate 5xx",
             [("sum by (arch) (rate(http_request_duration_seconds_count{%s, status_code=~\"5..\", arch=~\"monolith|microservices\"}[%s])) / sum by (arch) (rate(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[%s]))" % (EDGE, RI, EDGE, RI), "{{arch}}")],
             "percentunit"), 12, 9)
    for route, method in [("/api/products", "GET"), ("/api/orders", "POST")]:
        L.add(ts(f"Latency {method} {route}: p50 / p95 / p99", [
            ("histogram_quantile(%s, sum by (le, arch) (rate(http_request_duration_seconds_bucket{route=\"%s\", method=\"%s\", arch=~\"monolith|microservices\"}[%s])))" % (q, route, method, RI), "{{arch}} p%s" % p)
            for q, p in [("0.5", "50"), ("0.95", "95"), ("0.99", "99")]], "s",
            "Do not look only at the average: p95/p99 show what the slowest users experience."), 12, 9)
    L.add(ts("App CPU (cores)",
             [("sum by (arch) (rate(process_cpu_seconds_total{arch=~\"monolith|microservices\"}[%s]))" % RI, "{{arch}}")], "short"), 12, 9)
    L.add(ts("Efficiency: edge requests per CPU-second",
             [("sum by (arch) (rate(http_request_duration_seconds_count{%s, arch=~\"monolith|microservices\"}[%s])) / sum by (arch) (rate(process_cpu_seconds_total{arch=~\"monolith|microservices\"}[%s]))" % (EDGE, RI, RI), "{{arch}}")],
             "short"), 12, 9)
    return dashboard("tokoku-compare", "TokoKu: Monolith vs Microservices", L, [],
                     "Side-by-side comparison for analyzing experiment results.", refresh="10s", time_from="now-1h")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    for d in (overview(), containers(), compare()):
        path = OUT / f"{d['uid']}.json"
        path.write_text(json.dumps(d, indent=2, ensure_ascii=False), encoding="utf-8")
        print("wrote", path)
