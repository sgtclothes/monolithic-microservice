#!/usr/bin/env python3
"""Grafana dashboard generator for TokoKu.

The dashboard JSON files in dashboards/ are generated by this script. To add
or change a panel, edit this script and then run:

    python monitoring/grafana/generate_dashboards.py

Grafana reloads the JSON files automatically (provisioning) within ~10 seconds.
"""
import json
from pathlib import Path

OUT = Path(__file__).parent / "dashboards"
DS = {"type": "prometheus", "uid": "prometheus"}
RI = "$__rate_interval"

# Public routes (called by clients). /internal/* endpoints = service-to-service traffic.
EDGE = 'route=~"/api/.*"'


class Layout:
    """Lays out panels left to right on a 24-column grid."""

    def __init__(self):
        self.x = 0
        self.y = 0
        self.row_h = 0
        self.panels = []
        self.next_id = 1

    def _place(self, w, h):
        if self.x + w > 24:
            self.x = 0
            self.y += self.row_h
            self.row_h = 0
        pos = {"x": self.x, "y": self.y, "w": w, "h": h}
        self.x += w
        self.row_h = max(self.row_h, h)
        return pos

    def row(self, title):
        if self.x:
            self.y += self.row_h
        self.x, self.row_h = 0, 0
        self.panels.append({"type": "row", "title": title, "id": self.next_id, "collapsed": False,
                            "gridPos": {"x": 0, "y": self.y, "w": 24, "h": 1}, "panels": []})
        self.next_id += 1
        self.y += 1

    def add(self, panel, w, h):
        panel["id"] = self.next_id
        panel["gridPos"] = self._place(w, h)
        self.next_id += 1
        self.panels.append(panel)


def targets(queries):
    out = []
    for i, q in enumerate(queries):
        expr, legend = q if isinstance(q, tuple) else (q, "")
        out.append({"datasource": DS, "expr": expr, "legendFormat": legend, "refId": chr(65 + i)})
    return out


def ts(title, queries, unit="short", desc="", stack=False, min_zero=True):
    return {
        "type": "timeseries",
        "title": title,
        "description": desc,
        "datasource": DS,
        "targets": targets(queries),
        "fieldConfig": {
            "defaults": {
                "unit": unit,
                "min": 0 if min_zero else None,
                "custom": {
                    "lineWidth": 2,
                    "fillOpacity": 25 if stack else 8,
                    "showPoints": "never",
                    "spanNulls": True,
                    "stacking": {"mode": "normal" if stack else "none"},
                },
            },
            "overrides": [],
        },
        "options": {
            "legend": {"displayMode": "table", "placement": "bottom", "calcs": ["lastNotNull", "max", "mean"]},
            "tooltip": {"mode": "multi", "sort": "desc"},
        },
    }


def stat(title, queries, unit="short", desc="", thresholds=None, decimals=None):
    steps = thresholds or [{"color": "blue", "value": None}]
    return {
        "type": "stat",
        "title": title,
        "description": desc,
        "datasource": DS,
        "targets": [dict(t, instant=True, range=False) for t in targets(queries)],
        "fieldConfig": {"defaults": {"unit": unit, "decimals": decimals,
                                     "thresholds": {"mode": "absolute", "steps": steps}},
                        "overrides": []},
        "options": {"reduceOptions": {"calcs": ["lastNotNull"]}, "colorMode": "background",
                    "graphMode": "none", "textMode": "value_and_name", "orientation": "horizontal"},
    }


def text(title, content):
    return {"type": "text", "title": title, "options": {"mode": "markdown", "content": content}}


def dashboard(uid, title, layout, variables, desc, refresh="5s", time_from="now-30m"):
    return {
        "uid": uid,
        "title": title,
        "description": desc,
        "tags": ["tokoku"],
        "timezone": "browser",
        "editable": True,
        "graphTooltip": 1,  # crosshair shared across panels -> easy to correlate metrics
        "refresh": refresh,
        "time": {"from": time_from, "to": "now"},
        "schemaVersion": 39,
        "templating": {"list": variables},
        "panels": layout.panels,
        "links": [{"title": "TokoKu dashboards", "type": "dashboards", "tags": ["tokoku"], "asDropdown": True}],
    }


def custom_var(name, label, values, default_all=True):
    opts = [{"text": "All", "value": "$__all", "selected": default_all}] + [
        {"text": v, "value": v, "selected": False} for v in values]
    return {
        "name": name, "label": label, "type": "custom", "query": ",".join(values),
        "multi": True, "includeAll": True, "allValue": "|".join(values),
        "current": {"text": ["All"], "value": ["$__all"]}, "options": opts,
    }


ARCH_VAR = custom_var("arch", "Architecture", ["monolith", "microservices"])
A = 'arch=~"$arch"'


# =====================================================================
# 1. LIVE DEMO
# =====================================================================
def overview():
    L = Layout()
    L.add(text("How to read this dashboard", (
        "**Goal:** correlate *load* (k6) with *performance* (latency, errors) and *resources* (CPU, memory) "
        "on the same time axis. Hover over one panel and the time cursor moves on every other panel too.\n\n"
        "Phases as load grows: **Linear** (latency flat) → **Saturation** (latency creeps up, resources near their limit) → "
        "**Breaking** (latency spikes, errors rise) → **Collapse** (mass timeouts).  "
        "See also the *Containers (cAdvisor)* dashboard for CPU vs limit and throttling.")), 24, 3)

    L.row("① Load from k6 (client side)")
    L.add(ts("Active virtual users", [("sum by (arch) (k6_vus{%s})" % A, "{{arch}}")], "short",
             "Number of k6 virtual users currently running"), 6, 8)
    L.add(ts("Requests/sec (k6)", [("sum by (arch) (rate(k6_http_reqs_total{%s}[%s]))" % (A, RI), "{{arch}}")], "reqps"), 6, 8)
    L.add(ts("Latency p95 per endpoint (k6)", [("max by (arch, name) (k6_http_req_duration_p95{%s})" % A, "{{arch}} {{name}}")], "s",
             "Latency as seen by the client, including the gateway and network"), 6, 8)
    L.add(ts("Error rate (k6)", [("avg by (arch) (k6_http_req_failed_rate{%s})" % A, "{{arch}}")], "percentunit",
             "Share of failed requests (status >= 400 or timeout)"), 6, 8)

    L.row("② Application: RED (Rate, Errors, Duration)")
    L.add(ts("Throughput per service (including internal traffic)",
             [("sum by (arch, service) (rate(http_request_duration_seconds_count{%s, route!=\"/health\"}[%s]))" % (A, RI), "{{arch}} · {{service}}")],
             "reqps", "In microservices, 1 checkout = several service-to-service requests (internal traffic amplification)"), 8, 9)
    L.add(ts("Latency p95 per route",
             [("histogram_quantile(0.95, sum by (le, arch, service, route) (rate(http_request_duration_seconds_bucket{%s, route!=\"/health\"}[%s])))" % (A, RI),
               "{{arch}} · {{service}} {{route}}")], "s"), 8, 9)
    L.add(ts("Error 5xx per service",
             [("sum by (arch, service, route) (rate(http_request_duration_seconds_count{%s, status_code=~\"5..\"}[%s]))" % (A, RI), "{{arch}} · {{service}} {{route}}")],
             "reqps"), 8, 9)
    L.add(ts("Network hop cost: outbound call latency p95",
             [("histogram_quantile(0.95, sum by (le, arch, service, target) (rate(outbound_request_duration_seconds_bucket{%s}[%s])))" % (A, RI),
               "{{arch}} · {{service}} → {{target}}")], "s",
             "The monolith only calls third parties. Microservices also call other services over the network."), 8, 9)
    L.add(ts("Checkout results per second",
             [("sum by (arch, status) (rate(tokoku_orders_total{%s}[%s]))" % (A, RI), "{{arch}} · {{status}}")], "reqps"), 8, 9)
    L.add(ts("Logins per second (CPU-bound)",
             [("sum by (arch, result) (rate(tokoku_logins_total{%s}[%s]))" % (A, RI), "{{arch}} · {{result}}")], "reqps"), 8, 9)

    L.row("③ Resources (USE) per app process")
    L.add(ts("CPU used (cores) per service",
             [("sum by (arch, service) (rate(process_cpu_seconds_total{%s, service!=\"thirdparty-mock\"}[%s]))" % (A, RI), "{{arch}} · {{service}}")],
             "short", "1.0 = one full core. Compare with the container CPU limit."), 8, 9)
    L.add(ts("Memory (RSS) per service",
             [("sum by (arch, service) (process_resident_memory_bytes{%s, service!=\"thirdparty-mock\"})" % A, "{{arch}} · {{service}}")], "bytes"), 8, 9)
    L.add(ts("Event loop lag p99 (Node.js)",
             [("max by (arch, service) (nodejs_eventloop_lag_p99_seconds{%s, service!=\"thirdparty-mock\"})" % A, "{{arch}} · {{service}}")], "s",
             "A sharp rise means the process is CPU-busy and every request in that process has to wait (noisy neighbor)."), 8, 9)
    L.add(ts("DB pool: waiting connections",
             [("sum by (arch, service) (db_pool_connections{%s, state=\"waiting\"})" % A, "{{arch}} · {{service}}")], "short",
             "Constantly > 0 = database bottleneck or pool too small"), 8, 9)
    L.add(ts("DB query latency p95",
             [("histogram_quantile(0.95, sum by (le, arch, service) (rate(db_query_duration_seconds_bucket{%s}[%s])))" % (A, RI), "{{arch}} · {{service}}")], "s"), 8, 9)
    L.add(ts("Active replicas",
             [("count by (svc) (up{job=~\"monolith|microservices\"} == 1)", "{{svc}}")], "short",
             "Changes on scale out (docker compose --scale ...)"), 8, 9)

    L.row("④ Async, message broker & third parties")
    L.add(ts("Email notifications per second",
             [("sum by (arch, mode, status) (rate(tokoku_notifications_total{%s}[%s]))" % (A, RI), "{{arch}} · {{mode}} · {{status}}")], "reqps"), 8, 9)
    L.add(ts("Notification queue (backlog)",
             [("sum by (queue) (rabbitmq_queue_messages_ready)", "RabbitMQ ready · {{queue}}"),
              ("sum by (queue) (rabbitmq_queue_messages_unacked)", "RabbitMQ unacked · {{queue}}"),
              ("sum(tokoku_notification_backlog{%s})" % A, "monolith in-memory")], "short",
             "When the email provider is down, messages pile up in the queue and drain once it recovers."), 8, 9)
    L.add(ts("Requests to third parties",
             [("sum by (api, result) (rate(thirdparty_requests_total[%s]))" % RI, "{{api}} · {{result}}")], "reqps"), 8, 9)
    return dashboard("tokoku-overview", "TokoKu: Live Demo", L, [ARCH_VAR],
                     "Main demo dashboard: k6 load, application RED metrics, resources, and queues.")


